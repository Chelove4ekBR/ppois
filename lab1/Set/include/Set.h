#pragma once

#include <iostream>
#include <string>
#include <vector>
#include <algorithm>
#include <cmath>

/**
 * @brief Класс, представляющий математическое множество.
 *
 * Множество может содержать как атомарные элементы (например, символы или строки),
 * так и другие множества, обеспечивая поддержку сложной вложенности.
 * Класс автоматически поддерживает уникальность элементов и их сортировку (нормализацию).
 */
class Set
{
public:
    /**
     * @brief Структура, представляющая элемент множества (узел).
     *
     * Элемент может быть либо неделимым атомом, либо подмножеством (содержать другие узлы).
     */
    struct Node
    {
    private:
        bool is_set;                ///< Флаг, указывающий, является ли узел множеством (true) или атомом (false).
        std::string atom;           ///< Текстовое значение атома (используется, если is_set == false).
        std::vector<Node> children; ///< Дочерние элементы подмножества (используется, если is_set == true).

        friend class Set;

    public:
        /**
         * @brief Конструктор по умолчанию. Создает пустой атом.
         */
        Node();

        /**
         * @brief Конструктор для создания атомарного элемента.
         * @param atom_val Строковое значение атома.
         */
        Node(const std::string &atom_val);

        /**
         * @brief Конструктор для создания элемента-подмножества.
         * @param children_val Вектор дочерних узлов (элементов подмножества).
         */
        Node(const std::vector<Node> &children_val);

        /**
         * @brief Геттер: возвращает true, если узел является множеством, иначе false.
         * @return Флаг типа узла.
         */
        bool is_set_node() const;

        /**
         * @brief Геттер: возвращает строковое значение атома.
         * @return Константная ссылка на атом (пустая строка, если узел — множество).
         */
        const std::string &get_atom() const;

        /**
         * @brief Геттер: возвращает вектор дочерних узлов подмножества.
         * @return Константная ссылка на вектор детей (пустой, если узел — атом).
         */
        const std::vector<Node> &get_children() const;

        /**
         * @brief Оператор проверки на равенство двух элементов.
         * @param other Элемент для сравнения.
         * @return true, если элементы (и все их вложения) идентичны, иначе false.
         */
        bool operator==(const Node &other) const;

        /**
         * @brief Оператор проверки на неравенство.
         * @param other Элемент для сравнения.
         * @return true, если элементы различны, иначе false.
         */
        bool operator!=(const Node &other) const;

        /**
         * @brief Оператор "меньше" для строгого упорядочивания элементов.
         * Используется для сортировки и нормализации структуры множества.
         * @param other Элемент для сравнения.
         * @return true, если текущий элемент лексикографически или структурно меньше other.
         */
        bool operator<(const Node &other) const;

        /**
         * @brief Преобразует узел в строковое представление.
         * @return Строка, представляющая атом (например, "a") или множество (например, "{a, b}").
         */
        std::string to_string() const;
    };

private:
    std::vector<Node> Nodes; ///< Вектор элементов текущего множества.

    /**
     * @brief Нормализует множество.
     *
     * Метод рекурсивно обходит вложенные множества, сортирует элементы
     * и удаляет дубликаты для поддержания математических свойств множества.
     */
    void normalize();

    /**
     * @brief Вспомогательный метод для рекурсивного парсинга узла из строки.
     * @param str Строка для разбора.
     * @param pos Текущая позиция чтения в строке (передается по ссылке).
     * @return Разобранный узел (Node).
     */
    static Node parse_Node_recursive(const std::string &str, size_t &pos);

public:
    /**
     * @brief Конструктор по умолчанию. Создает пустое множество.
     */
    Set();

    /**
     * @brief Конструктор, создающий множество из заданного вектора элементов.
     * @param elems Вектор элементов, из которых будет сформировано множество.
     */
    Set(const std::vector<Node> &elems);

    /**
     * @brief Проверяет множество на пустоту.
     * @return true, если множество не содержит элементов, иначе false.
     */
    bool empty() const;

    /**
     * @brief Вычисляет мощность (количество элементов на верхнем уровне) множества.
     * @return Количество элементов множества.
     */
    int size() const;

    /**
     * @brief Полностью очищает множество, удаляя из него все элементы.
     */
    void clear();

    /**
     * @brief Проверяет, принадлежит ли элемент текущему множеству.
     * @param elem Искомый элемент.
     * @return true, если элемент найден в множестве, иначе false.
     */
    bool contains(const Node &elem) const;

    /**
     * @brief Добавляет новый элемент в множество.
     * @param elem Элемент для добавления.
     * @return true, если элемент успешно добавлен, false - если такой элемент уже существует.
     */
    bool add(const Node &elem);

    /**
     * @brief Удаляет указанный элемент из множества.
     * @param elem Элемент, который нужно удалить.
     * @return true, если элемент найден и успешно удален, иначе false.
     */
    bool remove(const Node &elem);

    /**
     * @brief Оператор индексации. Альтернативный способ проверить принадлежность элемента множеству (аналог contains).
     * @param elem Искомый элемент.
     * @return true, если элемент принадлежит множеству, иначе false.
     */
    bool operator[](const Node &elem) const;

    /**
     * @brief Операция объединения двух множеств.
     * @param other Второе множество.
     * @return Новое множество, содержащее все элементы из обоих множеств (без дубликатов).
     */
    Set operator+(const Set &other) const;
    Set &operator+=(const Set &other);
    Set &operator+=(const Node &elem);

    /**
     * @brief Операция пересечения двух множеств.
     * @param other Второе множество.
     * @return Новое множество, содержащее только общие элементы обоих множеств.
     */
    Set operator*(const Set &other) const;
    Set &operator*=(const Set &other);

    /**
     * @brief Операция разности множеств (A \ B).
     * @param other Второе множество (вычитаемое).
     * @return Новое множество, содержащее элементы из первого множества, которых нет во втором.
     */
    Set operator-(const Set &other) const;
    Set &operator-=(const Set &other);
    Set &operator-=(const Node &elem);

    /**
     * @brief Строит булеан множества (множество всех подмножеств).
     * @return Булеан множества.
     */
    Set power_set() const;

    /**
     * @brief Оператор проверки двух множеств на абсолютное равенство.
     * @param other Множество для сравнения.
     * @return true, если все элементы множеств идентичны, иначе false.
     */
    bool operator==(const Set &other) const;

    /**
     * @brief Оператор проверки двух множеств на неравенство.
     * @param other Множество для сравнения.
     * @return true, если множества различаются хотя бы одним элементом, иначе false.
     */
    bool operator!=(const Set &other) const;

    /**
     * @brief Преобразует структуру множества в человекочитаемую строку.
     * @return Строка формата "{a, {b, c}}".
     */
    std::string to_string() const;

    /**
     * @brief Статический метод для парсинга полной строки в объект множества.
     * @param str Входная строка (например, "{a, b, {c}}").
     * @return Сформированный объект Set.
     */
    static Set parse(const std::string &str);

    /**
     * @brief Статический метод для парсинга отдельного узла из строки.
     * @param str Входная строка для одиночного элемента.
     * @return Сформированный объект Node.
     */
    static Node parse_Node(const std::string &str);

    /**
     * @brief Перегрузка оператора вывода множества в поток.
     */
    friend std::ostream &operator<<(std::ostream &out, const Set &s);

    /**
     * @brief Перегрузка оператора ввода множества из потока.
     */
    friend std::istream &operator>>(std::istream &in, Set &s);
};